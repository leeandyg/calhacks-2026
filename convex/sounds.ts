import { ConvexError, v } from "convex/values";
import { internal } from "./_generated/api.js";
import type { Id } from "./_generated/dataModel.js";
import { action, internalMutation, query, type QueryCtx } from "./_generated/server.js";
import { requestSound } from "./elevenlabs.js";

// Generated sounds, stored once in Convex file storage and shared by every browser and deployment, so a
// description is paid for once (about 600 credits per 15 s loop). src/audio/generated.ts calls `request`;
// whoever claims a missing sound generates it, and anyone asking meanwhile watches `get` until it's ready.
// No sign-in needed, like GET /api/sound. Server-only: the key is read from the Convex deployment's env.

const kind = v.union(v.literal("bed"), v.literal("event"));
const args = { kind, query: v.string() };
const STALE_MS = 60_000; // a "generating" row older than this was abandoned (ElevenLabs times out at 25 s)

type Claim = { status: "ready"; url: string } | { status: "waiting" } | { status: "claimed"; id: Id<"sounds"> };

function find(ctx: QueryCtx, key: { kind: "bed" | "event"; query: string }) {
  return ctx.db.query("sounds")
    .withIndex("by_key", (q) => q.eq("kind", key.kind).eq("query", key.query)).unique();
}

/** The stored sound's status, and its URL once ready. */
export const get = query({
  args,
  handler: async (ctx, key) => {
    const sound = await find(ctx, key);
    if (!sound) return null;
    return { status: sound.status, url: sound.storageId ? await ctx.storage.getUrl(sound.storageId) : null };
  },
});

/** Ready, being generated by someone else, or claimed for the caller to generate. Runs as a transaction. */
export const claim = internalMutation({
  args,
  handler: async (ctx, key): Promise<Claim> => {
    const sound = await find(ctx, key);
    const url = sound?.status === "ready" && sound.storageId ? await ctx.storage.getUrl(sound.storageId) : null;
    if (url) return { status: "ready", url };
    if (sound?.status === "generating" && Date.now() - sound.updatedAt < STALE_MS) return { status: "waiting" };
    // Missing, failed, abandoned, or its file is gone: generate it again
    const fields = { status: "generating" as const, storageId: undefined, updatedAt: Date.now() };
    if (sound) {
      await ctx.db.patch(sound._id, fields);
      return { status: "claimed", id: sound._id };
    }
    return { status: "claimed", id: await ctx.db.insert("sounds", { ...key, ...fields }) };
  },
});

export const finish = internalMutation({
  args: { id: v.id("sounds"), storageId: v.id("_storage") },
  handler: async (ctx, { id, storageId }) => {
    await ctx.db.patch(id, { status: "ready", storageId, updatedAt: Date.now() });
  },
});

export const fail = internalMutation({
  args: { id: v.id("sounds") },
  handler: async (ctx, { id }) => {
    await ctx.db.patch(id, { status: "failed", updatedAt: Date.now() });
  },
});

/** The sound's URL, generating it first if nobody has. Null while someone else generates it: watch `get`. */
export const request = action({
  args,
  handler: async (ctx, key): Promise<string | null> => {
    if (!key.query.trim() || key.query.length > 300) throw new ConvexError("Send a description of 1-300 characters.");
    const claim = await ctx.runMutation(internal.sounds.claim, key);
    if (claim.status === "ready") return claim.url;
    if (claim.status === "waiting") return null;

    try {
      const apiKey = process.env.ELEVENLABS_API_KEY?.trim();
      if (!apiKey) throw new Error("ELEVENLABS_API_KEY is not set in this Convex deployment");
      const res = await requestSound(key.kind, key.query, apiKey);
      // Never pass on provider error bodies: they can contain request details.
      if (!res.ok) throw new Error(`ElevenLabs returned ${res.status}`);
      const storageId = await ctx.storage.store(await res.blob());
      const url = await ctx.storage.getUrl(storageId);
      if (!url) throw new Error("the stored sound has no URL");
      await ctx.runMutation(internal.sounds.finish, { id: claim.id, storageId });
      return url;
    } catch (error) {
      await ctx.runMutation(internal.sounds.fail, { id: claim.id });
      console.warn(`generating "${key.query}" failed:`, error instanceof Error ? error.message : "unknown error");
      throw new ConvexError("This sound could not be generated.");
    }
  },
});
